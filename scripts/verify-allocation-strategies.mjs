import assert from 'node:assert/strict';
import { chromium } from 'playwright';

const base = process.env.ERETAIL_BASE_URL || 'http://127.0.0.1:3011';
const testUsername = process.env.ERETAIL_TEST_USERNAME || 'allocation';
const testPassword = process.env.ERETAIL_TEST_PASSWORD || 'local';
const testLocation = process.env.ERETAIL_TEST_LOCATION || 'UWH';
const suffix = Date.now().toString().slice(-8);
const apiName = `API Allocation ${suffix}`;
const login = await fetch(`${base}/api/auth/login`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ username: testUsername, password: testPassword }) });
assert.equal(login.status, 200, 'The isolated administrator must authenticate before calling WMS APIs.');
const sessionCookie = (login.headers.get('set-cookie') || '').split(';', 1)[0];
assert.match(sessionCookie, /^dmills_session=[a-f0-9]{64}$/);
const send = async (method, body) => {
  const response = await fetch(`${base}/api/allocation-strategies`, { method, headers: { 'content-type': 'application/json', cookie: sessionCookie }, body: method === 'GET' ? undefined : JSON.stringify(body) });
  return { response, json: await response.json() };
};
const query = (overrides = {}) => ({ action: 'search', REQ_SEARCH_FLAG: true, rows: 20, page: 1, sidx: 'crtDate', sord: 'desc', strategyId: '', strategyName: '', locCode: '-1', status: '-1', ...overrides });
const meta = await send('GET');
assert.equal(meta.response.status, 200);
assert.ok(meta.json.locations.some(([code]) => code === testLocation));
assert.ok(meta.json.zones.length, 'The isolated WMS Zone workflow must run first.');
const inventoryEvents = async () => {
  const response = await fetch(`${base}/api/inventory-sync/central/events`, { headers: { cookie: sessionCookie } });
  assert.equal(response.status, 200);
  return (await response.json()).map((event) => event.event_key).sort();
};
const eventsBefore = await inventoryEvents();
for (const size of [20, 50, 100, 200]) {
  const result = await send('POST', query({ rows: size }));
  assert.equal(result.response.status, 200);
  assert.equal(result.json.rows, size);
  assert.ok(result.json.allocMasterDTOs.length <= size);
  for (const key of ['rows', 'total', 'page', 'records', 'allocMasterDTOs']) assert.ok(key in result.json);
}
let invalid = await send('POST', { action: 'save' });
assert.equal(invalid.response.status, 400);
assert.equal(invalid.json.error, 'Strategy Name is manadatory');
invalid = await send('POST', { action: 'save', strategyName: 'Missing Location' });
assert.equal(invalid.response.status, 400);
assert.equal(invalid.json.error, 'Location is manadatory');
invalid = await send('POST', { action: 'validate-step', step: { uom: 'Each', binLocType: '1', casePackUOM: 'Case', priority: '', sortRule: '4', invBucket: '10' }, steps: [] });
assert.equal(invalid.response.status, 400);
assert.equal(invalid.json.error, 'Priority cannot be blank');
const step = { uom: 'Each', binLocType: '1', casePackUOM: 'Case', priority: '1', zone: meta.json.zones[0], sortRule: '4', invBucket: '10' };
const valid = { action: 'save', strategyName: apiName, locCode: testLocation, overrideSKU: true, overrideShelf: false, steps: [step] };
const created = await send('POST', valid);
assert.equal(created.response.status, 201);
assert.equal(created.json.row.status, 'Pending');
const missingUpdate = await send('PUT', { ...valid, id: Number.MAX_SAFE_INTEGER, strategyId: 'ALS999999', action: 'save' });
assert.equal(missingUpdate.response.status, 404, 'An update for an unknown strategy must not silently create a new strategy.');
const duplicateCreate = await send('POST', { ...valid, strategyId: created.json.row.strategyId });
assert.equal(duplicateCreate.response.status, 409, 'A create request must not overwrite an existing strategy by its display id.');
const stillOne = await send('POST', query({ strategyId: created.json.row.strategyId }));
assert.equal(stillOne.json.records, 1);
const confirmed = await send('PUT', { ...valid, id: created.json.row.id, strategyId: created.json.row.strategyId, action: 'confirm' });
assert.equal(confirmed.response.status, 200);
assert.equal(confirmed.json.row.status, 'Confirmed');
const found = await send('POST', query({ strategyId: created.json.row.strategyId, status: '1' }));
assert.equal(found.json.records, 1);
assert.equal(found.json.allocMasterDTOs[0].stepsCount, '1');
const removed = await send('DELETE', { id: created.json.row.id });
assert.equal(removed.response.status, 200);
assert.deepEqual(await inventoryEvents(), eventsBefore, 'Saving/confirming strategy metadata must not mutate inventory.');

const browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE ? { executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE } : {}) });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('pageerror', (error) => errors.push(error.message));
page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()); });
try {
  await page.goto(base);
  await page.getByLabel('Login Id').fill(testUsername);
  await page.getByLabel('Password').fill(testPassword);
  await page.getByRole('button', { name: 'Login', exact: true }).click();
  await page.waitForURL('**/app/dashboard');
  await page.goto(`${base}/app/wms/allocation-strategies`);
  await page.getByRole('status').getByText('Order Allocate does not apply them', { exact: false }).waitFor();
  for (const action of ['Search', 'Reset', 'Add New']) await page.getByRole('button', { name: action, exact: true }).last().waitFor();
  for (const heading of ['Strategy ID', 'Strategy Name', 'Location', 'Override SKU Rotation', 'Override Shelf Life', 'Status', 'Steps Count']) await page.getByRole('columnheader', { name: heading, exact: true }).waitFor();
  for (const size of ['20', '50', '100', '200']) await page.getByLabel('Records per Page').selectOption(size);
  await page.getByRole('button', { name: 'Search', exact: true }).last().click();
  await page.getByText('No records to view', { exact: true }).last().waitFor();
  await page.getByRole('button', { name: 'Add New', exact: true }).last().click();
  for (const label of ['Strategy ID', 'Strategy Name*', 'Remark', 'Override SKU LIFO/FIFO', 'Override Shelf Life', 'Status', 'Location*', 'Step No', 'UOM*', 'Bin Location Type*', 'Case pack UOM', 'Zone', 'Inventory Bucket *', 'Sort Rule*', 'Priority*']) await page.getByLabel(label, { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await page.getByText('Strategy Name is manadatory', { exact: true }).waitFor();
  const uiName = `UI Allocation ${suffix}`;
  await page.getByLabel('Strategy Name*', { exact: true }).fill(uiName);
  await page.getByLabel('Location*', { exact: true }).selectOption(testLocation);
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await page.getByText('Strategy Detail cannot be blank', { exact: true }).waitFor();
  errors.length = 0;
  await page.getByLabel('UOM*', { exact: true }).selectOption('Each');
  await page.getByLabel('Bin Location Type*', { exact: true }).selectOption('1');
  await page.getByLabel('Case pack UOM', { exact: true }).selectOption('Case');
  await page.getByLabel('Zone', { exact: true }).selectOption(meta.json.zones[0]);
  await page.getByLabel('Inventory Bucket *', { exact: true }).selectOption('10');
  await page.getByLabel('Sort Rule*', { exact: true }).selectOption('4');
  await page.getByLabel('Priority*', { exact: true }).fill('1');
  await page.getByRole('button', { name: 'Add', exact: true }).click();
  const saveResponse = page.waitForResponse((response) => response.url().endsWith('/api/allocation-strategies') && response.request().method() === 'POST' && response.status() === 201);
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  const uiCreated = await (await saveResponse).json();
  assert.equal(uiCreated.row.strategyName, uiName);
  assert.equal(uiCreated.row.locCode, testLocation);
  await page.getByText('Allocation strategy saved succesfully', { exact: true }).waitFor();
  const strategyId = uiCreated.row.strategyId;
  assert.match(strategyId, /^ALS/);
  const confirmResponse = page.waitForResponse((response) => response.url().endsWith('/api/allocation-strategies') && response.request().method() === 'PUT');
  await page.getByRole('button', { name: 'Confirm', exact: true }).click();
  assert.equal((await confirmResponse).status(), 200);
  await page.getByText('Allocation strategy has been confirmed successfully', { exact: true }).waitFor();
  const confirmedReadback = await send('POST', query({ strategyId, status: '1' }));
  assert.equal(confirmedReadback.json.records, 1);
  assert.equal(confirmedReadback.json.allocMasterDTOs[0].strategyName, uiName);
  await page.getByRole('button', { name: 'Audit', exact: true }).click();
  const audit = page.getByRole('dialog', { name: 'Audit Details' });
  const auditText = await audit.innerText();
  assert.equal(uiCreated.row.created_by, testUsername);
  assert.ok(auditText.includes(`Created By: ${uiCreated.row.created_by}`));
  assert.ok(auditText.includes(`Modified By: ${confirmedReadback.json.allocMasterDTOs[0].modified_by}`));
  await page.getByRole('button', { name: 'Close modal', exact: true }).click();
  page.once('dialog', async (dialog) => { assert.equal(dialog.message(), 'Do you really want to remove this Allocation Strategy?'); await dialog.accept(); });
  const deleteResponse = page.waitForResponse((response) => response.url().endsWith('/api/allocation-strategies') && response.request().method() === 'DELETE');
  await page.getByRole('button', { name: 'Remove', exact: true }).first().click();
  assert.equal((await deleteResponse).status(), 200);
  await page.getByText('Allocation strategy deleted successfully', { exact: true }).waitFor();
  assert.deepEqual(errors, []);
  assert.deepEqual(await inventoryEvents(), eventsBefore);
  console.log('PASS Manage Allocation Strategies: authenticated config create/confirm/remove, step validation, audit actor, paging, and no Central Inventory mutation. Confirmation is metadata only until Order Allocate is connected.');
} finally {
  await browser.close();
}
