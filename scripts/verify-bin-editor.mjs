import assert from 'node:assert/strict';
import { chromium } from 'playwright';

const base = process.env.ERETAIL_BASE_URL || 'http://127.0.0.1:3011';
const testUsername = process.env.ERETAIL_TEST_USERNAME || 'bin-editor';
const testPassword = process.env.ERETAIL_TEST_PASSWORD || 'local';
const testLocation = process.env.ERETAIL_TEST_LOCATION || 'UWH';
const suffix = Date.now().toString().slice(-8);
const apiBinCode = `AB${suffix}`;
const uiBinCode = `UB${suffix}`;
const login = await fetch(`${base}/api/auth/login`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ username: testUsername, password: testPassword }) });
assert.equal(login.status, 200, 'The isolated administrator must authenticate before calling WMS APIs.');
const sessionCookie = (login.headers.get('set-cookie') || '').split(';', 1)[0];
assert.match(sessionCookie, /^dmills_session=[a-f0-9]{64}$/);
const send = async (method, body) => {
  const response = await fetch(`${base}/api/bin-editor`, { method, headers: { 'content-type': 'application/json', cookie: sessionCookie }, body: method === 'GET' ? undefined : JSON.stringify(body) });
  return { response, json: await response.json() };
};
const meta = await send('GET');
assert.equal(meta.response.status, 200);
assert.ok(meta.json.zones.length, 'The isolated WMS Zone verifier must create a zone first.');
assert.ok(meta.json.locations.some((location) => location.code === testLocation), `Configured location ${testLocation} is required.`);
const bad = await send('POST', {});
assert.equal(bad.response.status, 400);
assert.equal(bad.json.error, 'Please enter bin code');
const valid = { locCode: testLocation, binCode: apiBinCode, binType: '2', binFlag: '2', status: true, invBucket: '10', zone: meta.json.zones[0], binLocationType: '1', clients: [], commingleItem: true, commingleLot: true, approximateUnits: '10', thresholdQty: '5' };
const created = await send('POST', valid);
assert.equal(created.response.status, 201);
assert.equal(created.json.row.binCode, apiBinCode);
const duplicate = await send('POST', valid);
assert.equal(duplicate.response.status, 409);
assert.equal(duplicate.json.error, 'This Bin is already exist with this location.');
const invalidThreshold = await send('PUT', { ...valid, id: created.json.row.id, thresholdQty: '11' });
assert.equal(invalidThreshold.response.status, 400);
assert.equal(invalidThreshold.json.error, 'ThresHold Qty must be less than or equal to Approx. No Of Units');
const updated = await send('PUT', { ...valid, id: created.json.row.id, aisle: 'A1', thresholdQty: '4' });
assert.equal(updated.response.status, 200);
assert.equal(updated.json.row.aisle, 'A1');
const enquiry = await fetch(`${base}/api/bin-enquiry`, { method: 'POST', headers: { 'content-type': 'application/json', cookie: sessionCookie }, body: JSON.stringify({ REQ_SEARCH_FLAG: true, rows: 20, page: 1, sidx: 'binCode', sord: 'desc', locCode: testLocation, binCode: apiBinCode, status: '1' }) }).then((response) => response.json());
assert.equal(enquiry.records, 1);
assert.equal(enquiry.gridModel[0].loc_code, testLocation);

const browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE ? { executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE } : {}) });
const page = await browser.newPage();
const errors = [];
page.on('pageerror', (error) => errors.push(error.message));
page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()); });
try {
  await page.goto(base);
  await page.getByLabel('Login Id').fill(testUsername);
  await page.getByLabel('Password').fill(testPassword);
  await page.getByRole('button', { name: 'Login', exact: true }).click();
  await page.waitForURL('**/app/dashboard');
  await page.goto(`${base}/app/wms/bin-editor`);
  for (const action of ['Audit', 'Save', 'Reset', 'Delete']) await page.getByRole('button', { name: action, exact: true }).waitFor();
  for (const tab of ['Bin Details', 'UDF', 'Video Capture Configuration']) await page.getByRole('button', { name: tab, exact: true }).waitFor();
  for (const label of ['Site Location*', 'BIN Code*', 'BIN Type*', 'BIN Flag*', 'Is Active', 'BIN Bucket*', 'Zone*', 'Aisle', 'Sequence No', 'Bin Location Type*', 'Allowed UOMs', 'X Coordinate', 'Y Coordinate', 'Z Coordinate', 'Commingle Item', 'Commingle Lot', 'Approx. No Of Units', 'Threshold Qty']) await page.getByLabel(label, { exact: true }).waitFor();
  assert.equal(await page.getByLabel('Site Location*', { exact: true }).isDisabled(), false);
  assert.ok(await page.getByLabel('Site Location*', { exact: true }).locator('option').evaluateAll((options, expected) => options.some((option) => option.value === expected), testLocation));
  await page.getByRole('button', { name: 'UDF', exact: true }).click();
  for (const label of ['UDF1', 'UDF2', 'UDF3', 'UDF4', 'UDF5']) await page.getByLabel(label, { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Video Capture Configuration', exact: true }).click();
  assert.equal(await page.getByLabel('Camera Id', { exact: true }).isDisabled(), true);
  await page.getByRole('button', { name: 'Bin Details', exact: true }).click();
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await page.getByText('Please enter bin code', { exact: true }).waitFor();
  await page.getByLabel('Site Location*', { exact: true }).selectOption(testLocation);
  await page.getByLabel('BIN Code*', { exact: true }).fill(uiBinCode);
  await page.getByLabel('BIN Bucket*', { exact: true }).selectOption('10');
  await page.getByLabel('Zone*', { exact: true }).selectOption(meta.json.zones[0]);
  await page.getByLabel('Bin Location Type*', { exact: true }).selectOption('1');
  await page.getByLabel('Approx. No Of Units', { exact: true }).fill('10');
  await page.getByLabel('Threshold Qty', { exact: true }).fill('11');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await page.getByText('ThresHold Qty must be less than or equal to Approx. No Of Units', { exact: true }).waitFor();
  await page.getByLabel('Threshold Qty', { exact: true }).fill('5');
  const createResponse = page.waitForResponse((response) => response.url().endsWith('/api/bin-editor') && response.request().method() === 'POST');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  const createdResponse = await createResponse;
  if (createdResponse.status() !== 201) throw new Error(`Bin Create/Edit returned HTTP ${createdResponse.status()}: ${await createdResponse.text()}`);
  const uiCreated = await createdResponse.json();
  assert.equal(uiCreated.row.binCode, uiBinCode);
  await page.getByText('Data saved successfully.', { exact: true }).waitFor();
  assert.equal(await page.getByLabel('BIN Code*', { exact: true }).isDisabled(), true);
  await page.getByLabel('Aisle', { exact: true }).fill('UIA');
  const updateResponse = page.waitForResponse((response) => response.url().endsWith('/api/bin-editor') && response.request().method() === 'PUT');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  assert.equal((await updateResponse).status(), 200);
  await page.getByText('Data saved successfully.', { exact: true }).waitFor();
  const updatedReadback = await send('GET');
  assert.equal(updatedReadback.json.bins.find((row) => row.binCode === uiBinCode)?.aisle, 'UIA');
  await page.getByRole('button', { name: 'Audit', exact: true }).click();
  const audit = page.getByRole('dialog', { name: 'Audit Details' });
  assert.equal(await audit.getByText(testUsername, { exact: true }).count(), 2, 'The audit modal must show the creating and modifying actor.');
  await page.getByRole('button', { name: 'Close modal', exact: true }).click();
  let confirmation = '';
  page.once('dialog', async (dialog) => { confirmation = dialog.message(); await dialog.accept(); });
  const deleteResponse = page.waitForResponse((response) => response.url().endsWith('/api/bin-editor') && response.request().method() === 'DELETE');
  await page.getByRole('button', { name: 'Delete', exact: true }).click();
  assert.equal(confirmation, 'Do you really want to Delete this Bin?');
  assert.equal((await deleteResponse).status(), 200);
  await page.getByText('Bin deleted successfully.', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Reset', exact: true }).click();
  assert.equal(await page.getByLabel('BIN Code*', { exact: true }).inputValue(), '');
  assert.deepEqual(errors, []);
  console.log('PASS Bin Create/Edit: authenticated MongoDB create/edit/readback/delete, duplicate and threshold guards, configured location/zone dependencies, all tabs, audit actor, and clean browser state.');
} finally {
  await browser.close();
}
const deleted = await send('DELETE', { id: created.json.row.id });
assert.equal(deleted.response.status, 200);
