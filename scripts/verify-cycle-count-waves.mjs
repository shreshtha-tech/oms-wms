import assert from 'node:assert/strict';
import { chromium } from 'playwright';

const base = process.env.ERETAIL_BASE_URL || 'http://127.0.0.1:3002';
const testUsername = process.env.ERETAIL_TEST_USERNAME || 'cycle';
const testPassword = process.env.ERETAIL_TEST_PASSWORD || 'local';
const testLocation = process.env.ERETAIL_TEST_LOCATION || 'UWH';
const suffix = Date.now().toString().slice(-8);
const apiWaveName = `API Cycle Wave ${suffix}`;
const login = await fetch(`${base}/api/auth/login`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ username: testUsername, password: testPassword }) });
assert.equal(login.status, 200, 'The isolated administrator must authenticate before calling WMS APIs.');
const sessionCookie = (login.headers.get('set-cookie') || '').split(';', 1)[0];
assert.match(sessionCookie, /^dmills_session=[a-f0-9]{64}$/);
const send = async (method, body) => {
  const response = await fetch(`${base}/api/cycle-count-waves`, { method, headers: { 'content-type': 'application/json', cookie: sessionCookie }, body: method === 'GET' ? undefined : JSON.stringify(body) });
  return { response, json: await response.json() };
};
const query = (overrides = {}) => ({ action: 'search', REQ_SEARCH_FLAG: true, rows: 20, page: 1, sidx: 'updDate', sord: 'desc', clientId: '', locCode: '-1', waveId: '', waveDesc: '', wavetype: '-1', schMethod: '-1', toDate: '', fromStartDate: '', toStartDate: '', fromEndDate: '', toEndDate: '', status: '-1', ...overrides });
const meta = await send('GET');
assert.equal(meta.response.status, 200);
assert.ok(meta.json.locations.some(([code]) => code === testLocation));
assert.ok(meta.json.zones.length, 'The isolated WMS Zone workflow must run first.');
const inventoryEvents = async () => {
  const response = await fetch(`${base}/api/inventory-sync/central/events`, { headers: { cookie: sessionCookie } });
  assert.equal(response.status, 200);
  return (await response.json()).map((event) => event.event_key).sort();
};
const eventsBefore = await inventoryEvents();
for (const size of [20, 50, 100, 200]) {
  const result = await send('POST', query({ rows: size }));
  assert.equal(result.response.status, 200);
  assert.equal(result.json.rows, size);
  for (const key of ['rows', 'total', 'page', 'records']) assert.ok(key in result.json);
}
const missing = await send('POST', {});
assert.equal(missing.response.status, 400);
assert.equal(missing.json.error, 'Cycle Wave Name is mandatory');
const startDate = new Date().toISOString().slice(0, 10);
const endDate = new Date(Date.now() + 86_400_000).toISOString().slice(0, 10);
const invalidDates = await send('POST', { waveName: 'Invalid Date Range', startDate: endDate, endDate: startDate, ruleParameter: '5', schedulingMethod: '1', locCode: testLocation });
assert.equal(invalidDates.response.status, 400);
assert.equal(invalidDates.json.error, 'End Date should be greater than Start Date');
const waveBase = { waveName: apiWaveName, waveStatus: '1', periodType: '1', startDate, endDate, locCode: testLocation, waveType: '1', ruleParameter: '5', schedulingMethod: '1', pickZone: meta.json.zones[0] };
const missingZone = await send('POST', { ...waveBase, pickZone: '' });
assert.equal(missingZone.response.status, 400);
assert.equal(missingZone.json.error, 'Pick Zone is mandatory.');
const unknownZone = await send('POST', { ...waveBase, pickZone: 'NO-SUCH-ZONE' });
assert.equal(unknownZone.response.status, 400);
assert.equal(unknownZone.json.error, 'Select a configured Pick Zone.');
const missingCategory = await send('POST', { ...waveBase, ruleParameter: '1', categoryName: '' });
assert.equal(missingCategory.response.status, 400);
assert.equal(missingCategory.json.error, 'SKU Category is mandatory for the selected rule parameter.');
const apiWave = await send('POST', waveBase);
assert.equal(apiWave.response.status, 201);
assert.match(apiWave.json.row.waveId, /^CCW/);
const apiReadback = await send('POST', query({ waveId: apiWave.json.row.waveId }));
assert.equal(apiReadback.json.records, 1);
assert.equal(apiReadback.json.cycleCountDTOs[0].waveDesc, apiWaveName);
const missingUpdate = await send('PUT', { ...waveBase, id: -1 });
assert.equal(missingUpdate.response.status, 404);

const browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE ? { executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE } : {}) });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('pageerror', (error) => errors.push(error.message));
page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()); });
try {
  await page.goto(base);
  await page.getByLabel('Login Id').fill(testUsername);
  await page.getByLabel('Password').fill(testPassword);
  await page.getByRole('button', { name: 'Login', exact: true }).click();
  await page.waitForURL('**/app/dashboard');
  await page.goto(`${base}/app/wms/cycle-count-waves`);
  for (const action of ['Search', 'Add New', 'Reset']) await page.getByRole('button', { name: action, exact: true }).last().waitFor();
  for (const heading of ['Location', 'Wave Id', 'Wave Description', 'Type', 'Scheduling Method', 'Start Date', 'End Date', 'Last Run Time', 'Status', 'Audit']) await page.getByRole('columnheader', { name: heading, exact: true }).waitFor();
  for (const size of ['20', '50', '100', '200']) await page.getByLabel('Records per Page').selectOption(size);
  await page.getByRole('button', { name: 'Add New', exact: true }).last().click();
  for (const label of ['Cycle Wave id:', 'Cycle Wave Name:', 'Status', 'Period Type', 'Start Date', 'End Date', 'Location', 'Type', 'Rule Parameter', 'Pick Zone *', 'Scheduling Method']) await page.getByLabel(label, { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await page.getByText('Cycle Wave Name is mandatory', { exact: true }).waitFor();
  assert.deepEqual(errors, ['Failed to load resource: the server responded with a status of 400 (Bad Request)'], 'The only browser error should be the expected server-side required-field validation.');
  errors.length = 0;
  const uiWaveName = `UI Cycle Wave ${suffix}`;
  await page.getByLabel('Cycle Wave Name:', { exact: true }).fill(uiWaveName);
  await page.getByLabel('Start Date', { exact: true }).fill(startDate);
  await page.getByLabel('End Date', { exact: true }).fill(endDate);
  await page.getByLabel('Location', { exact: true }).selectOption(testLocation);
  await page.getByLabel('Rule Parameter', { exact: true }).selectOption('5');
  await page.getByLabel('Pick Zone *', { exact: true }).selectOption(meta.json.zones[0]);
  await page.getByLabel('Scheduling Method', { exact: true }).selectOption('1');
  const createResponse = page.waitForResponse((response) => response.url().endsWith('/api/cycle-count-waves') && response.request().method() === 'POST' && response.status() === 201);
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  const uiCreated = await (await createResponse).json();
  assert.equal(uiCreated.row.waveDesc, uiWaveName);
  assert.equal(uiCreated.row.locCode, testLocation);
  await page.getByText('Cycle Count Wave saved successfully', { exact: true }).waitFor();
  assert.ok(await page.getByLabel('Cycle Wave id:', { exact: true }).inputValue());
  await page.goto(`${base}/app/wms/cycle-count-waves`);
  await page.getByRole('button', { name: 'Search', exact: true }).last().click();
  const grid = page.locator('table').filter({ has: page.getByRole('columnheader', { name: 'Wave Id', exact: true }) });
  const uiRow = grid.getByRole('row').filter({ hasText: uiCreated.row.waveId });
  await uiRow.waitFor();
  assert.match(await uiRow.innerText(), new RegExp(uiWaveName));
  await uiRow.getByRole('button', { name: uiCreated.row.waveId, exact: true }).click();
  await page.getByLabel('Cycle Wave Name:', { exact: true }).fill(`${uiWaveName} Updated`);
  await page.getByLabel('Status', { exact: true }).selectOption('0');
  const updateResponse = page.waitForResponse((response) => response.url().endsWith('/api/cycle-count-waves') && response.request().method() === 'PUT');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  assert.equal((await updateResponse).status(), 200);
  const updated = await send('POST', query({ waveId: uiCreated.row.waveId, status: '0' }));
  assert.equal(updated.json.records, 1);
  assert.equal(updated.json.cycleCountDTOs[0].waveDesc, `${uiWaveName} Updated`);
  assert.equal(updated.json.cycleCountDTOs[0].status, 'InActive');
  assert.deepEqual(await inventoryEvents(), eventsBefore, 'Wave setup must not post inventory or count events.');
  assert.deepEqual(errors, []);
  assert.equal(await page.locator('vite-error-overlay').count(), 0);
  console.log('PASS Manage Cycle Count Wave: authenticated metadata create/edit/readback, date/rule/location/zone validation, remote paging/search, missing-update rejection, and no Central Inventory event changes. Wave setup does not execute or post a count.');
} finally {
  await browser.close();
}
