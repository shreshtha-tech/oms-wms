import assert from 'node:assert/strict';
const mongoFixture=process.env.VENDOR_MONGO_FIXTURE==='true';
if(mongoFixture){
 const url=new URL(process.env.MONGODB_URI||'');
 assert.equal(url.hostname,'127.0.0.1');
 assert.match(process.env.MONGODB_DB||'',/^codexqa_vendor_/);
}else process.env.MONGODB_URI='';
process.env.NODE_ENV='test';process.env.DMILLS_REQUIRE_PERSISTENCE='false';
const store=await import('../api/mongo.js');
assert.equal(await store.waitForDataReady(),mongoFixture?'mongo':'memory');
const handler=(await import('../api/vendors.js')).default;
const call=async(method,body)=>{const res={statusCode:200,status(code){this.statusCode=code;return this;},json(payload){this.payload=payload;return this;},setHeader(){}};await handler({method,body,user:{username:'fixture-actor'}},res);return res;};
const initial=await call('POST',{vendor_code:'BOUNDARY-1',vendor_name:'First'});assert.equal(initial.statusCode,201);
const injected=await call('POST',{id:initial.payload.id,vendor_code:'BOUNDARY-2',vendor_name:'Second',audit:[{by:'forged'}]});
assert.equal(injected.statusCode,201);
assert.notEqual(injected.payload.id,initial.payload.id,'Client must not select an existing vendor identity');
assert.deepEqual(injected.payload.audit.map(row=>row.by),['fixture-actor']);
const renamed=await call('PUT',{id:initial.payload.id,vendor_name:'Renamed',vendor_code:'FORGED',audit:[{by:'forged'}]});
assert.equal(renamed.statusCode,200);assert.equal(renamed.payload.vendor_code,'BOUNDARY-1');
assert.deepEqual(renamed.payload.audit.map(row=>row.by),['fixture-actor','fixture-actor']);
assert.equal((await call('DELETE',{id:initial.payload.id})).statusCode,409);
const race=await Promise.all([call('POST',{vendor_code:'RACE',vendor_name:'A'}),call('POST',{vendor_code:'RACE',vendor_name:'B'})]);
assert.deepEqual(race.map(row=>row.statusCode).sort(),[201,409]);
assert.equal((await store.find('vendors',{vendor_code:'RACE'})).length,1);
const burst=await Promise.all(Array.from({length:20},(_,index)=>call('POST',{vendor_code:'BURST',vendor_name:`Fixture ${index}`})));
assert.equal(burst.filter(row=>row.statusCode===201).length,1);
assert.equal(burst.filter(row=>row.statusCode===409).length,19);
assert.equal((await store.find('vendors',{vendor_code:'BURST'})).length,1);
console.log(JSON.stringify({identityAndAudit:'PASS',duplicateCreateStatuses:race.map(row=>row.statusCode),duplicateRows:(await store.find('vendors',{vendor_code:'RACE'})).length,evidenceLayer:mongoFixture?'disposable local MongoDB':'isolated in-memory; Mongo concurrency unverified'}));

const beforeAudit=(await store.findOne('vendors',{id:initial.payload.id})).audit.length;
const saves=await Promise.all(Array.from({length:10},(_,index)=>call('PUT',{id:initial.payload.id,vendor_name:`Concurrent ${index}`})));
assert.ok(saves.every(row=>row.statusCode===200));
assert.equal((await store.findOne('vendors',{id:initial.payload.id})).audit.length,beforeAudit+10,'Each successful concurrent save must retain its audit event');
await store.update('vendors',initial.payload.id,{audit:'corrupt-fixture'});
const beforeCorrupt=(await store.findOne('vendors',{id:initial.payload.id})).vendor_name;
assert.equal((await call('PUT',{id:initial.payload.id,vendor_name:'Must not persist'})).statusCode,409);
assert.equal((await store.findOne('vendors',{id:initial.payload.id})).vendor_name,beforeCorrupt);
assert.equal((await store.findOne('vendors',{id:initial.payload.id})).audit,'corrupt-fixture');
console.log(`PASS: ten concurrent vendor saves retain ten audit entries; malformed history rejects without changing fields. ${mongoFixture?'Disposable MongoDB':'Memory'} evidence only.`);
const disjoint=await call('POST',{vendor_code:'DISJOINT',vendor_name:'Original'});
const changes=await Promise.all([call('PUT',{id:disjoint.payload.id,vendor_name:'Newest'}),call('PUT',{id:disjoint.payload.id,city:'Fixture City'})]);
assert.ok(changes.every(row=>row.statusCode===200));
const merged=await store.findOne('vendors',{id:disjoint.payload.id});
assert.equal(merged.vendor_name,'Newest','An omitted name must not restore a stale snapshot');
assert.equal(merged.city,'Fixture City');
assert.equal(merged.audit.length,3);
assert.equal((await call('PUT',{id:disjoint.payload.id,vendor_name:'   '})).statusCode,400);
assert.equal((await call('PUT',{id:disjoint.payload.id,vendor_name:null,state:'Fixture State'})).statusCode,200);
assert.equal((await store.findOne('vendors',{id:disjoint.payload.id})).vendor_name,'Newest');
console.log(`PASS: concurrent rename and city-only update preserve both changes/history; blank name rejects and null name preserves current value. ${mongoFixture?'Disposable MongoDB':'Memory'} evidence only.`);
