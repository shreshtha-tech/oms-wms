import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { chromium } from 'playwright';

const base = process.env.ERETAIL_BASE_URL || 'http://127.0.0.1:3011';
const testUsername = process.env.ERETAIL_TEST_USERNAME || 'bin-enquiry';
const testPassword = process.env.ERETAIL_TEST_PASSWORD || 'local';
const testLocation = process.env.ERETAIL_TEST_LOCATION || 'UWH';
const suffix = Date.now().toString().slice(-8);
const binCode = `EQ${suffix}`;
const login = await fetch(`${base}/api/auth/login`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ username: testUsername, password: testPassword }) });
assert.equal(login.status, 200, 'The isolated administrator must authenticate before calling WMS APIs.');
const sessionCookie = (login.headers.get('set-cookie') || '').split(';', 1)[0];
assert.match(sessionCookie, /^dmills_session=[a-f0-9]{64}$/);
const send = async (path, method, body) => {
  const response = await fetch(`${base}${path}`, { method, headers: { 'content-type': 'application/json', cookie: sessionCookie }, body: body === undefined ? undefined : JSON.stringify(body) });
  return { response, json: await response.json() };
};
const meta = await send('/api/bin-editor', 'GET');
assert.equal(meta.response.status, 200);
assert.ok(meta.json.zones.length, 'The isolated WMS Zone workflow must create a zone before bin tests.');
assert.ok(meta.json.locations.some((location) => location.code === testLocation), `Configured location ${testLocation} is required.`);
const binPayload = { locCode: testLocation, binCode, binType: '2', binFlag: '2', status: true, invBucket: '10', zone: meta.json.zones[0], aisle: 'QA1', binLocationType: '1', clients: [], commingleItem: true, commingleLot: true, approximateUnits: '10', thresholdQty: '5' };
const created = await send('/api/bin-editor', 'POST', binPayload);
assert.equal(created.response.status, 201);
assert.equal(created.json.row.binCode, binCode);
const query = (overrides = {}) => ({ action: 'search', _search: true, rows: 20, page: 1, sidx: 'binCode', sord: 'desc', locCode: '', binCode: '', binType: '-1', zone: '', invBucket: '', status: '1', fromEmptyBins: '', toEmptyBins: '', defRetBin: false, defRTOBin: false, defInbBin: false, defCrossDockBin: false, defUSNExcessBin: false, aisle: '', binloactionType: '-1', REQ_SEARCH_FLAG: true, doFetchCount: true, ...overrides });
const search = async (overrides = {}) => send('/api/bin-enquiry', 'POST', query(overrides));
for (const size of [20, 50, 100, 200]) {
  const result = await search({ rows: size, locCode: testLocation, binCode, doFetchCount: false });
  assert.equal(result.response.status, 200);
  assert.equal(result.json.rows, size);
  assert.equal(result.json.records, 1);
  assert.ok(result.json.gridModel.length <= size);
  assert.deepEqual(result.json.binMasterDTOs, result.json.gridModel);
}
const exact = await search({ locCode: testLocation, binCode, zone: meta.json.zones[0], aisle: 'QA1' });
assert.equal(exact.json.records, 1);
assert.equal(exact.json.gridModel[0].bin_code, binCode);
assert.equal(exact.json.gridModel[0].bin_qty, null, 'Missing central bin balance must remain unknown, not display as zero.');
const none = await search({ locCode: testLocation, binCode: 'NO-SUCH-BIN' });
assert.equal(none.json.records, 0);
const unsupportedEmptyFilter = await search({ locCode: testLocation, fromEmptyBins: '1' });
assert.equal(unsupportedEmptyFilter.response.status, 501);
assert.match(unsupportedEmptyFilter.json.error, /unavailable until bin balances and default-bin mappings are connected to Central Inventory/);
const unsupportedDefaultFilter = await search({ locCode: testLocation, defInbBin: true });
assert.equal(unsupportedDefaultFilter.response.status, 501);

const browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE ? { executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE } : {}) });
const page = await browser.newPage();
const errors = [];
page.on('pageerror', (error) => errors.push(error.message));
page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()); });
try {
  await page.goto(base);
  await page.getByLabel('Login Id').fill(testUsername);
  await page.getByLabel('Password').fill(testPassword);
  await page.getByRole('button', { name: 'Login', exact: true }).click();
  await page.waitForURL('**/app/dashboard');
  await page.goto(`${base}/app/wms/bin-enquiry`);
  await page.getByRole('button', { name: 'Search', exact: true }).last().waitFor();
  await page.getByRole('cell', { name: 'No records to view', exact: true }).waitFor();
  for (const action of ['Search', 'Reset', 'Advance Search', 'Download', 'Print', 'Add new']) await page.getByRole('button', { name: action, exact: true }).last().waitFor();
  for (const heading of ['Location', 'Bin Code', 'Zone', 'Bin Bucket', 'Bin Location Type', 'Approx. No Of Units', 'Bin Qty', 'Status', 'Commingle Lot', 'Commingle Item']) await page.getByRole('columnheader', { name: heading, exact: true }).waitFor();
  const grid = page.locator('table').filter({ has: page.getByRole('columnheader', { name: 'Bin Code', exact: true }) });
  await grid.locator('thead tr').nth(1).locator('input').nth(1).fill(binCode);
  const searchRequest = page.waitForRequest((request) => request.url().endsWith('/api/bin-enquiry') && request.method() === 'POST');
  await page.getByRole('button', { name: 'Search', exact: true }).last().click();
  const searchPayload = (await searchRequest).postDataJSON();
  assert.equal(searchPayload.binCode, binCode);
  assert.equal(searchPayload.status, '1');
  const resultRow = page.getByRole('row').filter({ hasText: binCode });
  await resultRow.waitFor();
  await resultRow.getByLabel('Bin quantity unavailable').waitFor();
  await page.getByRole('button', { name: 'Reset', exact: true }).last().click();
  assert.equal(await grid.locator('thead tr').nth(1).locator('input').nth(1).inputValue(), '');
  await page.getByRole('cell', { name: 'No records to view', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Search', exact: true }).last().click();
  await page.getByRole('cell', { name: binCode, exact: true }).waitFor();
  await page.getByRole('button', { name: 'Advance Search', exact: true }).last().click();
  const dialog = page.getByRole('dialog', { name: 'Advance Search' });
  for (const label of ['Site Location', 'Bin Type', 'Status', 'Aisle', 'Empty Bins From', 'Empty Bins To']) await dialog.getByLabel(label).waitFor();
  assert.deepEqual(await dialog.getByLabel('Status').locator('option').allTextContents(), ['Yes', 'No']);
  assert.equal(await dialog.getByLabel('Empty Bins From').isDisabled(), true);
  assert.equal(await dialog.getByLabel('Empty Bins To').isDisabled(), true);
  for (const label of ['Default Inbound Bin', 'Default Return Bin', 'Default RTO Bin', 'Default Cross Dock Bin', 'Default USN Excess Bin']) assert.equal(await dialog.getByLabel(label).isDisabled(), true);
  await dialog.getByLabel('Site Location').selectOption(testLocation);
  await dialog.getByLabel('Aisle').fill('QA1');
  const advancedRequest = page.waitForRequest((request) => request.url().endsWith('/api/bin-enquiry') && request.method() === 'POST');
  await dialog.getByRole('button', { name: 'Search', exact: true }).click();
  const advancedPayload = (await advancedRequest).postDataJSON();
  assert.equal(advancedPayload.locCode, testLocation);
  assert.equal(advancedPayload.aisle, 'QA1');
  await page.getByRole('cell', { name: binCode, exact: true }).waitFor();
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download', exact: true }).last().click();
  const download = await downloadPromise;
  assert.equal(download.suggestedFilename(), 'bin-enquiry.csv');
  assert.match(await readFile(await download.path(), 'utf8'), new RegExp(binCode));
  for (const size of ['20', '50', '100', '200']) await page.getByLabel('Records per Page').selectOption(size);
  await page.getByRole('button', { name: 'Add new', exact: true }).last().click();
  await page.waitForURL('**/app/wms/bin-editor');
  await page.getByRole('heading', { name: 'Bin Create/Edit', exact: true }).first().waitFor();
  assert.deepEqual(errors, []);
  console.log('PASS Bin Enquiry: authenticated API filters/paging, search/reset, advanced location/aisle filters, CSV download, create navigation, unknown bin quantity display, unsupported empty/default filters fail closed, and clean browser state. Print output remains outside this check.');
} finally {
  await browser.close();
}
