import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import ExcelJS from 'exceljs';
import JSZip from 'jszip';
const require = createRequire(import.meta.url);
const excelRequire = createRequire(require.resolve('exceljs'));
const { v4 } = excelRequire('uuid');
assert.match(v4(), /^[a-f0-9]{8}-[a-f0-9]{4}-4[a-f0-9]{3}-[89ab][a-f0-9]{3}-[a-f0-9]{12}$/);
const workbook = new ExcelJS.Workbook();
const sheet = workbook.addWorksheet('Fixture');
sheet.addRow(['SKU', 'Quantity', 'Formula']);
sheet.addRow(['owned-fixture', 12, { formula: 'B2*2', result: 24 }]);
sheet.addRow(['owned-second', 5]);
sheet.getCell('A1').font = { bold: true };
sheet.addConditionalFormatting({ ref: 'B2:B3', rules: [{ type: 'dataBar', cfvo: [{ type: 'min' }, { type: 'max' }], color: { argb: 'FF008800' }, showValue: true }] });
const buffer = await workbook.xlsx.writeBuffer();
const zip = await JSZip.loadAsync(buffer);
const xml = await zip.file('xl/worksheets/sheet1.xml').async('string');
assert.match(xml, /[A-F0-9]{8}-[A-F0-9]{4}-4[A-F0-9]{3}-[89AB][A-F0-9]{3}-[A-F0-9]{12}/);
const restored = new ExcelJS.Workbook();
await restored.xlsx.load(buffer);
const result = restored.getWorksheet('Fixture');
assert.equal(result.getCell('A2').value, 'owned-fixture');
assert.equal(result.getCell('B2').value, 12);
assert.deepEqual(result.getCell('C2').value, { formula: 'B2*2', result: 24 });
assert.equal(result.getCell('A1').font.bold, true);
assert.equal(result.conditionalFormattings[0].rules[0].type, 'dataBar');
console.log('PASS: ExcelJS resolves patched UUID v4; data-bar extension IDs, values, formula and formatting survive XLSX round trip.');
