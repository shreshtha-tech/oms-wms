import assert from 'node:assert/strict';
import { observeLatency, latencySnapshot, metricSnapshot } from '../reliability/telemetry.js';
for (const value of [0, 1, 5, 6, 60000, 60001]) observeLatency('fixture_ms', { route: '/fixture' }, value);
for (const value of [-1, NaN, Infinity]) observeLatency('fixture_ms', { route: '/fixture' }, value);
const snapshot = latencySnapshot();
assert.equal(snapshot[0].count, 6);
assert.equal(snapshot[0].sumMs, 120013);
assert.equal(snapshot[0].maxMs, 60001);
assert.equal(snapshot[0].overflow, 1);
assert.equal(snapshot[0].buckets.find(bucket => bucket.le === 1).count, 2);
assert.equal(snapshot[0].buckets.find(bucket => bucket.le === 5).count, 3);
assert.equal(snapshot[0].buckets.at(-1).count, 5);
snapshot[0].buckets[0].count = 999;
assert.equal(latencySnapshot()[0].buckets[0].count, 2);
for (let i = 0; i < 600; i++) observeLatency('cardinality_fixture', { route: String(i) }, 1);
assert.equal(latencySnapshot().length, 512);
assert.ok(metricSnapshot().some(metric => metric.name === 'latency_series_dropped_total' && metric.value > 0));
observeLatency('fixture_ms', { route: '/fixture' }, 2);
assert.equal(latencySnapshot()[0].count, 7);
console.log('PASS: cumulative latency buckets, totals/max/overflow, invalid sample rejection, snapshot isolation and bounded cardinality with visible drops.');
