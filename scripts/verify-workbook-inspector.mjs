import assert from 'node:assert/strict';
import ExcelJS from 'exceljs';
import express from 'express';
import { inspectInventoryWorkbook } from '../inventory/workbook-inspector.js';
import { inventoryFilesApi } from '../inventory/files-api.js';
import { parseInventoryWorkbook } from '../inventory/workbook.js';

const book = new ExcelJS.Workbook();
const counts = book.addWorksheet('Physical counts');
counts.addRow(['SKU', 'SKU', 'Location', 'On hand', 'secret_token']);
counts.addRow(['SKU-A', 'SKU-A', 'WH-TEST', 5]);
counts.addRow(['SKU-A', 'SKU-A', 'WH-TEST', 5]);
counts.addRow([]);
counts.addRow(['SKU-B', 'SKU-B', 'WH-TEST', { formula: '2+3', result: 5 }]);
counts.mergeCells('F1:G1');
counts.getColumn(3).hidden = true;
const hidden = book.addWorksheet('Hidden input');
hidden.state = 'veryHidden';
hidden.addRow(['Internal field']);

const bytes = Buffer.from(await book.xlsx.writeBuffer());
const result = await inspectInventoryWorkbook(bytes, 'source.xlsx');
assert.equal(result.sheets.length, 2);
assert.match(result.sha256, /^[a-f0-9]{64}$/);
assert.equal(result.sheets[0].duplicateRowCount, 1);
assert.equal(result.sheets[0].blankRows, 1);
assert.equal(result.sheets[0].formulaCount, 1);
assert.deepEqual(result.sheets[0].mergedCellRanges, ['F1:G1']);
assert.deepEqual(result.sheets[0].hiddenColumns, [3]);
assert.deepEqual(result.sheets[0].duplicateHeaders, [{ label: 'sku', count: 2 }]);
assert.equal(result.sheets[0].firstRowLabels[4].label, '[redacted]');
assert.equal(result.sheets[0].candidateHeaderRows[0].row, 1);
assert.deepEqual(result.sheets[0].candidateHeaderRows[0].columns.map(column=>column.kind),['sku','sku','location','quantity']);
assert.equal(result.sheets[1].state, 'veryHidden');
assert.equal(JSON.stringify(result).includes('SKU-A'), false, 'Data-row values must not be printed');
const offsetBook=new ExcelJS.Workbook();
offsetBook.addWorksheet('Marketplace').addRows([['Report exported'],['SKU-A','WH-TEST'],['Seller SKU ID','Facility','Available Stock'],['SKU-B','WH-TEST',8]]);
const offset=await inspectInventoryWorkbook(Buffer.from(await offsetBook.xlsx.writeBuffer()),'offset.xlsx');
assert.equal(offset.sheets[0].candidateHeaderRows.length,1);
assert.equal(offset.sheets[0].candidateHeaderRows[0].row,3);
assert.deepEqual(offset.sheets[0].candidateHeaderRows[0].columns.map(column=>column.kind),['sku','location','quantity']);
assert.equal(JSON.stringify(offset.sheets[0].candidateHeaderRows).includes('SKU-A'),false);
const noCounts = new ExcelJS.Workbook();
noCounts.addWorksheet('Catalog').addRows([['SKU', 'Stock'], ['SKU-A', 50]]);
const missingSheet = await parseInventoryWorkbook(Buffer.from(await noCounts.xlsx.writeBuffer()), 'counts');
assert.equal(missingSheet.rows.length, 0);
assert.match(missingSheet.errors[0].message, /Physical counts worksheet/);
const missingQuantity = new ExcelJS.Workbook();
missingQuantity.addWorksheet('Physical counts').addRows([['SKU', 'Listed availability'], ['SKU-A', 50]]);
const noQuantity = await parseInventoryWorkbook(Buffer.from(await missingQuantity.xlsx.writeBuffer()), 'counts');
assert.equal(noQuantity.rows.length, 0);
assert.match(noQuantity.errors[0].message, /verified on-hand units/);
const mixed = new ExcelJS.Workbook();
mixed.addWorksheet('Physical counts').addRows([['SKU', 'On hand'], ['SKU-A', 7]]);
mixed.addWorksheet('Catalog').addRows([['SKU', 'Stock'], ['SKU-A', 500]]);
const physicalOnly = await parseInventoryWorkbook(Buffer.from(await mixed.xlsx.writeBuffer()), 'counts');
assert.deepEqual(physicalOnly.rows.map(row => row.stock), [7]);
const mappedBook = new ExcelJS.Workbook();
mappedBook.addWorksheet('Marketplace export').addRows([['Report title'], [], ['Seller SKU ID', 'Description', 'Stock'], ['SKU-001', 'Fixture', '1,250']]);
const mappedBytes = Buffer.from(await mappedBook.xlsx.writeBuffer());
const mapped = await parseInventoryWorkbook(mappedBytes, 'counts', { sheet:'Marketplace export', headerRow:3, sku:{column:1,header:'Seller SKU ID'}, quantity:{column:3,header:'Stock',format:'integer_grouped'} });
assert.equal(mapped.errors.length,0);
assert.deepEqual(mapped.rows.map(row=>({sku:row.sku,stock:row.stock,sheet:row.sheet,row:row.row})),[{sku:'SKU-001',stock:1250,sheet:'Marketplace export',row:4}]);
assert.match(mapped.rows[0].mappingSha256,/^[a-f0-9]{64}$/);
await assert.rejects(parseInventoryWorkbook(mappedBytes,'counts',{sheet:'Marketplace export',headerRow:3,sku:{column:1,header:'SKU'},quantity:{column:3,header:'Stock',format:'integer_grouped'}}),/header does not match/);
const numericSkuBook=new ExcelJS.Workbook();numericSkuBook.addWorksheet('Marketplace export').addRows([['Seller SKU ID','Stock'],[12345,1]]);
const numericSku=await parseInventoryWorkbook(Buffer.from(await numericSkuBook.xlsx.writeBuffer()),'counts',{sheet:'Marketplace export',headerRow:1,sku:{column:1,header:'Seller SKU ID'},quantity:{column:2,header:'Stock',format:'integer_plain'}});
assert.match(numericSku.errors[0].message,/stored as text/,'Numeric SKU cells are rejected to preserve exact identifiers');
const large = new ExcelJS.Workbook();
const largeCounts = large.addWorksheet('Physical counts');
largeCounts.addRow(['SKU', 'On hand']);
for (let row = 1; row <= 50_001; row++) largeCounts.addRow([`SKU-${row}`, row]);
const largeBytes = Buffer.from(await large.xlsx.writeBuffer());
const fiftyThousand = new ExcelJS.Workbook();
await fiftyThousand.xlsx.load(largeBytes);
fiftyThousand.getWorksheet('Physical counts').spliceRows(50_002, 1);
const allowedRows = await parseInventoryWorkbook(Buffer.from(await fiftyThousand.xlsx.writeBuffer()), 'counts');
assert.equal(allowedRows.rows.length, 50_000, 'Exactly 50,000 count rows are accepted');
await assert.rejects(parseInventoryWorkbook(largeBytes, 'counts'), /Maximum 50,000 rows per import/);
const app = express();
app.use(express.json({ limit: '10mb' }));
app.use(inventoryFilesApi);
const server = app.listen(0, '127.0.0.1');
try {
  await new Promise(resolve => server.once('listening', resolve));
  const url = `http://127.0.0.1:${server.address().port}/imports/inspect`;
  const response = await fetch(url, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ fileName: 'source.xlsx', base64: bytes.toString('base64') }) });
  assert.equal(response.status, 200);
  assert.equal(response.headers.get('cache-control'), 'no-store');
  const inspected = await response.json();
  assert.equal(inspected.sha256, result.sha256);
  assert.equal(JSON.stringify(inspected).includes('SKU-A'), false);
  const rejected = await fetch(url, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ fileName: 'source.csv', base64: bytes.toString('base64') }) });
  assert.equal(rejected.status, 400);
} finally {
  await new Promise((resolve, reject) => server.close(error => error ? reject(error) : resolve()));
}
console.log('PASS structural workbook inspection, data-row redaction and 50,000-row limit');
